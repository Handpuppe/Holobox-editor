import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const resourcesRoot = join(root, 'resources');
const outFile = join(root, 'src', 'media', 'generated', 'media-manifest.ts');

const VIDEO_EXT = new Set(['.mp4', '.webm', '.mov', '.m4v']);
const IMAGE_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp', '.avif', '.svg']);

const STOP = new Set(['staat', 'is', 'de', 'het', 'een', 'en', 'of', 'van']);

function walk(dir) {
  if (!existsSync(dir)) {
    return [];
  }
  const entries = readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(full));
    } else {
      files.push(full);
    }
  }
  return files;
}

function keywordsFromName(name) {
  const normalized = name.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase();
  const parts = normalized.split(/[^a-z0-9]+/).filter((part) => part.length > 1 && !STOP.has(part));
  return [...new Set(parts)].sort();
}

function publicUrl(relPosix) {
  return `/resources/${relPosix
    .split('/')
    .map((segment) => encodeURIComponent(segment))
    .join('/')}`;
}

function readMp4DurationSeconds(buffer) {
  const marker = Buffer.from('mvhd');
  const index = buffer.indexOf(marker);
  if (index < 0 || index + 24 > buffer.length) {
    return null;
  }
  const version = buffer[index + 4];
  try {
    if (version === 0) {
      const timescale = buffer.readUInt32BE(index + 16);
      const duration = buffer.readUInt32BE(index + 20);
      return timescale > 0 ? duration / timescale : null;
    }
    if (version === 1) {
      const timescale = buffer.readUInt32BE(index + 24);
      const duration = Number(buffer.readBigUInt64BE(index + 28));
      return timescale > 0 ? duration / timescale : null;
    }
  } catch {
    return null;
  }
  return null;
}

function classify(ext) {
  if (VIDEO_EXT.has(ext)) {
    return 'video';
  }
  if (IMAGE_EXT.has(ext)) {
    return 'image';
  }
  return null;
}

const files = walk(resourcesRoot);
const items = [];

for (const full of files) {
  const ext = extname(full).toLowerCase();
  const kind = classify(ext);
  if (!kind) {
    continue;
  }
  const rel = relative(resourcesRoot, full).split(sep).join('/');
  const moduleName = rel.split('/')[0];
  if (moduleName !== 'logopedie' && moduleName !== 'verpleegkunde') {
    continue;
  }
  const stats = statSync(full);
  const warnings = [];
  let durationSeconds = null;
  if (kind === 'video' && ext === '.mp4') {
    try {
      const buffer = readFileSync(full);
      durationSeconds = readMp4DurationSeconds(buffer);
      if (durationSeconds === null) {
        warnings.push('duration-unreadable');
      }
    } catch {
      warnings.push('duration-unreadable');
    }
  }
  items.push({
    relativePath: rel,
    module: moduleName,
    fileType: kind,
    extension: ext,
    sizeBytes: stats.size,
    normalizedName: rel.toLowerCase(),
    keywords: keywordsFromName(rel),
    durationSeconds,
    width: null,
    height: null,
    publicUrl: publicUrl(rel),
    warnings,
  });
}

items.sort((a, b) => a.relativePath.localeCompare(b.relativePath, 'nl'));

mkdirSync(dirname(outFile), { recursive: true });
const source = `/* Generated by scripts/generate-media-manifest.mjs. Do not edit by hand. */
export const mediaManifest = ${JSON.stringify({ generatedAt: new Date().toISOString(), items }, null, 2)} as const;
`;
writeFileSync(outFile, source, 'utf8');
process.stdout.write(`Wrote ${items.length} media items to ${relative(root, outFile)}\n`);
